/**
 * Self-host Brazil hub LCP hero from Cloudinary source.
 * Run: npm run optimize:brazil-hero
 * Re-run when brazil.hero.config.js fallback publicId/version changes.
 */
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');
const { cloudinaryImageUrl } = require('./routeLcpPreload.cjs');

const SOURCE_URL = cloudinaryImageUrl('Brazil/Brazil-hero', {
  width: 800,
  version: 1779448919,
});
const OUTPUT = path.join(__dirname, '../public/assets/brazil-hero-400.webp');
const INLINE_OUT = path.join(__dirname, 'brazil-hero-inline.cjs');
const WIDTH = 400;
const QUALITY = 78;

async function main() {
  const response = await fetch(SOURCE_URL);
  if (!response.ok) {
    throw new Error(`Failed to fetch hero: ${response.status} ${SOURCE_URL}`);
  }
  const buffer = Buffer.from(await response.arrayBuffer());
  const webpBuffer = await sharp(buffer)
    .resize(WIDTH)
    .webp({ quality: QUALITY, effort: 6 })
    .toBuffer();
  await fs.promises.writeFile(OUTPUT, webpBuffer);
  const dataUri = `data:image/webp;base64,${webpBuffer.toString('base64')}`;
  await fs.promises.writeFile(
    INLINE_OUT,
    '/** Generated by npm run optimize:brazil-hero — do not edit */\n' +
      `module.exports = { BRAZIL_HERO_DATA_URI: ${JSON.stringify(dataUri)} };\n`
  );
  console.log(
    `brazil-hero-400.webp: ${WIDTH}x${Math.round((WIDTH * 301) / 400)}, ` +
      `${(webpBuffer.length / 1024).toFixed(1)} KiB (+ inline data URI for /brazil HTML)`
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
