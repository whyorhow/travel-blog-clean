/**
 * Self-host Pantanal mobile LCP hero from Cloudinary source.
 * Run: npm run optimize:pantanal-hero
 * Source: pantanal.hero.config.js fallback tier.
 */
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');
const { cloudinaryImageUrl } = require('./routeLcpPreload.cjs');

const PANTANAL_HERO_ID = 'hero/fallback/pantanal/main';

const SOURCE_URL = cloudinaryImageUrl(PANTANAL_HERO_ID, { width: 800 });
const OUTPUT = path.join(__dirname, '../public/assets/pantanal-hero-400.webp');
const INLINE_OUT = path.join(__dirname, 'pantanal-hero-inline.cjs');
const WIDTH = 400;
const QUALITY = 78;

async function main() {
  const response = await fetch(SOURCE_URL);
  if (!response.ok) {
    throw new Error(`Failed to fetch hero: ${response.status} ${SOURCE_URL}`);
  }
  const buffer = Buffer.from(await response.arrayBuffer());
  const meta = await sharp(buffer).metadata();
  const webpBuffer = await sharp(buffer)
    .resize(WIDTH)
    .webp({ quality: QUALITY, effort: 6 })
    .toBuffer();
  await fs.promises.writeFile(OUTPUT, webpBuffer);
  const dataUri = `data:image/webp;base64,${webpBuffer.toString('base64')}`;
  await fs.promises.writeFile(
    INLINE_OUT,
    '/** Generated by npm run optimize:pantanal-hero — do not edit */\n' +
      'module.exports = { PANTANAL_HERO_DATA_URI: ' + JSON.stringify(dataUri) + ' };\n'
  );
  const height = meta.width && meta.height ? Math.round((WIDTH * meta.height) / meta.width) : 534;
  console.log(
    `pantanal-hero-400.webp: ${WIDTH}x${height}, ${(webpBuffer.length / 1024).toFixed(1)} KiB`
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
