/**
 * Self-host Greece mobile LCP hero from Cloudinary source.
 * Run: npm run optimize:greece-hero
 */
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');
const { cloudinaryImageUrl } = require('./routeLcpPreload.cjs');

const HERO_ID = "Greece/Greece-backup";
const SOURCE_URL = cloudinaryImageUrl(HERO_ID, { width: 800 });
const OUTPUT = path.join(__dirname, '../public/assets/greece-hero-400.webp');
const INLINE_OUT = path.join(__dirname, 'greece-hero-inline.cjs');
const WIDTH = 400;
const QUALITY = 72;

async function main() {
  const response = await fetch(SOURCE_URL);
  if (!response.ok) {
    throw new Error(`Failed to fetch hero: ${response.status} ${SOURCE_URL}`);
  }
  const buffer = Buffer.from(await response.arrayBuffer());
  const meta = await sharp(buffer).metadata();
  const webpBuffer = await sharp(buffer)
    .resize(WIDTH)
    .webp({ quality: QUALITY, effort: 6 })
    .toBuffer();
  await fs.promises.writeFile(OUTPUT, webpBuffer);
  const dataUri = `data:image/webp;base64,${webpBuffer.toString('base64')}`;
  const inlineBody =
    '/** Generated by npm run optimize:greece-hero — do not edit */\n' +
    'module.exports = { GREECE_HERO_DATA_URI: ' + JSON.stringify(dataUri) + ' };\n';
  await fs.promises.writeFile(INLINE_OUT, inlineBody);
  const height = meta.width && meta.height ? Math.round((WIDTH * meta.height) / meta.width) : 534;
  console.log(
    `greece-hero-400.webp: ${WIDTH}x${height}, ${(webpBuffer.length / 1024).toFixed(1)} KiB`
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
